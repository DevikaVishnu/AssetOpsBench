@needs_ap
def test_621_support_link_grounding(raw_traces):
    """Every grounding span and numeric transformation of the positive control."""
    fx = _load("aob-621-compare.trace.json")
    rec = raw_traces["621"]
    R = _texts_from_raw(fx, rec)["evi:621:R"]
    link = next(l for l in fx["semantic"]["links"] if l["relation"] == "supported_by")
    spans = link["raw_ref"]["spans"]
    pieces = [R[a:b] for a, b in spans]
    stamps, values = pieces[0::2], pieces[1::2]
    assert len(stamps) == len(values) == 8
    # timestamps: June 10, exact 15-minute steps, and no other timestamp in R
    times = [datetime.fromisoformat(s) for s in stamps]
    assert all(t.month == 6 and t.day == 10 for t in times)
    assert all(b - a == timedelta(minutes=15) for a, b in zip(times, times[1:]))
    assert re.findall(r'"timestamp": "([^"]+)"', R) == stamps
    # sensor key on every value line
    assert all(v.startswith('"Chiller 6 Tonnage": ') for v in values)
    # numeric rule, declared per proposition (D1)
    nm = fx["profile_local"]["numeric_matching"][0]
    assert nm["rule"] == "nearest_integer" and nm["proposition"] == link["source"]
    form = next(p["form"] for p in fx["semantic"]["propositions"] if p["id"] == link["source"])
    stated = [int(x) for x in re.search(r"values_rounded_to_integer=\[([^\]]*)\]", form).group(1).split(",")]
    assert [v["stated"] for v in nm["values"]] == stated
    for v, line, (a, b) in zip(nm["values"], values, spans[1::2]):
        sa, sb = v["source_span"]
        assert a <= sa and sb == b and R[sa:sb] == v["source"] == line.split(": ")[1]
        assert abs(float(v["source"]) - v["stated"]) < 0.5
    # the claim states these integers, in this order
    claim = fx["semantic"]["claims"][0]["raw_ref"]["text"]
    assert [int(x.replace(",", "")) for x in re.findall(r"\d[\d,]*", claim)[:8]] == stated
    # sensor and date are in the proposition; unit is not grounded anywhere delivered
    assert 'sensor="Chiller 6 Tonnage"' in form and 'date="June 10"' in form and "tons" not in form
    assert not re.search(r"\btons\b", R, re.I)
    inp = json.dumps(resolve(rec, "events[seq=157].input_batches[0]"))
    assert not re.search(r"\btons\b", inp, re.I)
    # span constraint: no grounding span lies in a claim's evidence
    assert link["target"] not in {c["evidence"] for c in fx["semantic"]["claims"]}


