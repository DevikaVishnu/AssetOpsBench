# --- helpers -----------------------------------------------------------------


def _sha(data: bytes | str) -> str:
    return hashlib.sha256(data.encode("utf-8") if isinstance(data, str) else data).hexdigest()


def _load(name: str) -> dict:
    return json.loads((FIXTURE_DIR / name).read_text(encoding="utf-8"))


_TOKEN = re.compile(r"([A-Za-z_]\w*)|\[(\w+)=([^\]]+)\]|\[(\d+)\]")


def resolve(record: dict, locator: str) -> Any:
    obj: Any = record
    for name, key, val, idx in _TOKEN.findall(locator):
        if name:
            obj = obj[name]
        elif key:
            matches = [x for x in obj if str(x.get(key)) == val]
            assert len(matches) == 1, f"{locator}: {len(matches)} matches"
            obj = matches[0]
        else:
            obj = obj[int(idx)]
    return obj


def _as_text(value: Any, text_form: str | None) -> str:
    if text_form == "content_list_text":
        assert isinstance(value, list) and all(p.get("type") == "text" for p in value)
        return "".join(p["text"] for p in value)
    assert isinstance(value, str)
    return value


def _subset(expected: Any, actual: Any, path: str = "") -> None:
    """Every key in ``expected`` must match ``actual``; lists match element-wise."""
    if isinstance(expected, dict):
        assert isinstance(actual, dict), f"{path}: expected object, got {actual!r}"
        for k, v in expected.items():
            assert k in actual, f"{path}.{k} missing in {sorted(actual)}"
            _subset(v, actual[k], f"{path}.{k}")
    elif isinstance(expected, list):
        assert isinstance(actual, list) and len(actual) == len(expected), f"{path}: {actual!r} != {expected!r}"
        for i, (e, a) in enumerate(zip(expected, actual)):
            _subset(e, a, f"{path}[{i}]")
    else:
        assert actual == expected, f"{path}: {actual!r} != {expected!r}"


def _run(comp: sc.Comparator, entry: dict) -> dict:
    rule, inp = entry["rule"], entry["inputs"]
    if rule == "O2":
        return comp.exposure_at(inp["event"], inp["item"], spans=inp.get("spans"))
    if rule == "claim_delivery":
        return comp.claim_delivery(inp["event"], inp["claim"])
    if rule == "O3":
        return comp.state_vs_evidence(inp["state"])
    raise AssertionError(rule)


