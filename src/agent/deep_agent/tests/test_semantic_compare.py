def raw_traces():
    """Raw traces for the real fixtures, read-only and re-hashed afterwards."""
    if not (AP_ROOT / "data" / "assetopsbench" / "runs").is_dir():
        pytest.skip("AP research repo not found")
    out, before = {}, {}
    for key, name in REAL.items():
        fx = _load(f"{name}.trace.json")
        path = AP_ROOT / fx["semantic"]["run"]["raw_ref"]["trace"]
        data = path.read_bytes()
        before[key] = (path, _sha(data))
        out[key] = json.loads(data)
