FORBIDDEN = ("conflicts_with", "revises", "CONFLICT", "REVISION", "causes", "contributes_to", "first_exposure", "PERSIST")


def _all_results(comp: sc.Comparator, key: str) -> list[dict]:
    return [_run(comp, e) for e in _load(f"{ALL[key]}.expected.json")["entries"]]


def test_no_forbidden_outputs_and_no_mutation():
    fx = _load("synthetic-compare.trace.json")
